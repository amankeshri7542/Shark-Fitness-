// Token contrast table (WCAG 1.4.3 text, 1.4.11 non-text) for both themes,
// computed from packages/design-tokens/src/sonar.css. Writes
// docs/ux-audit/contrast.md and docs/ux-audit/data/contrast.json.
// `node audit/contrast.mjs` (run by `pnpm -F @shark/e2e audit`).
import { mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import console from 'node:console';
import { DATA_DIR, DOCS_DIR, WORKSPACE_ROOT } from './lib/paths.mjs';
import { composite, contrastRatio, displayRatio, parseColor, parseThemes, verdict } from './lib/contrast.mjs';

/** Opaque surfaces text sits on (PRD 03 surface/canvas, raised, overlay). */
const SURFACES = ['abyss', 'hull', 'panel', 'overlay', 'shelf-top', 'shelf-mid'];
/** Tinted panels: a wash painted over the canvas (status panels, selected rows). */
const WASHES = ['wash-sonar', 'wash-sonar-soft', 'wash-flare', 'wash-chum', 'wash-kelp'];
/** Saturated fills that carry text (CTA, status badges). */
const FILLS = ['sonar', 'kelp', 'flare', 'chum'];
const TEXT = ['foam', 'foam-80', 'foam-65', 'foam-50', 'foam-45', 'foam-35', 'foam-25', 'sonar', 'sonar-dim', 'flare', 'kelp', 'chum'];
/** Non-text: hairlines that bound controls (inputs use --sf-line, buttons --sf-line-strong), the focus ring (--sf-sonar), chart marks. */
const NON_TEXT = ['line-10', 'line', 'line-strong', 'line-accent', 'sonar', 'chum', 'data-1', 'data-2', 'data-3', 'data-4', 'data-5', 'data-6', 'data-track'];

function sources(dir, out = []) {
  for (const name of readdirSync(dir)) {
    if (name === 'node_modules' || name === 'dist' || name === '__tests__' || name === 'test') continue;
    const path = join(dir, name);
    if (statSync(path).isDirectory()) sources(path, out);
    else if (/\.(tsx?|css|astro)$/.test(name) && !/\.test\./.test(name)) out.push(path);
  }
  return out;
}

/** How often each token is used as text colour / as a colour at all, across the three apps. */
function usage() {
  const files = ['apps/admin-web/src', 'apps/member-pwa/src', 'apps/website/src'].flatMap((d) => sources(resolve(WORKSPACE_ROOT, d)));
  const text = files.map((f) => readFileSync(f, 'utf8')).join('\n');
  const count = (re) => (text.match(re) ?? []).length;
  const result = {};
  for (const token of new Set([...TEXT, ...NON_TEXT, 'on-accent'])) {
    const esc = token.replace(/-/g, '\\-');
    result[token] = {
      textClass: count(new RegExp(`\\btext-${esc}(?![\\w-])`, 'g')),
      cssVar: count(new RegExp(`var\\(--sf-${esc}\\)`, 'g')),
    };
  }
  return result;
}

function hex({ r, g, b }) {
  return `#${[r, g, b].map((c) => Math.round(c).toString(16).padStart(2, '0')).join('')}`;
}

const css = readFileSync(resolve(WORKSPACE_ROOT, 'packages/design-tokens/src/sonar.css'), 'utf8');
const themes = parseThemes(css);
const used = usage();
const rows = [];

for (const [theme, tokens] of Object.entries(themes)) {
  const color = (name) => {
    const parsed = parseColor(tokens[name]);
    if (!parsed) throw new Error(`--sf-${name} in ${theme} is not a colour: ${tokens[name]}`);
    return parsed;
  };
  const canvas = color('abyss');
  const surfaces = [
    ...SURFACES.map((s) => ({ name: s, paint: color(s) })),
    ...WASHES.map((w) => ({ name: `${w} on abyss`, paint: composite(color(w), canvas) })),
    ...WASHES.map((w) => ({ name: `${w} on panel`, paint: composite(color(w), color('panel')) })),
  ];
  for (const surface of surfaces) {
    for (const token of TEXT) {
      const ratio = contrastRatio(color(token), surface.paint);
      rows.push({ theme, kind: 'text', token, surface: surface.name, surfaceHex: hex(surface.paint), ratio: displayRatio(ratio), verdict: verdict(ratio, 'text') });
    }
    for (const token of NON_TEXT) {
      const ratio = contrastRatio(color(token), surface.paint);
      rows.push({ theme, kind: 'non-text', token, surface: surface.name, surfaceHex: hex(surface.paint), ratio: displayRatio(ratio), verdict: verdict(ratio, 'non-text') });
    }
  }
  for (const fill of FILLS) {
    for (const token of ['on-accent']) {
      const ratio = contrastRatio(color(token), color(fill));
      rows.push({ theme, kind: 'text', token, surface: `${fill} (fill)`, surfaceHex: hex(color(fill)), ratio: displayRatio(ratio), verdict: verdict(ratio, 'text') });
    }
  }
}

mkdirSync(DATA_DIR, { recursive: true });
writeFileSync(resolve(DATA_DIR, 'contrast.json'), `${JSON.stringify({ usage: used, rows }, null, 2)}\n`);

// ——— Markdown ———————————————————————————————————————————————
const mark = { pass: 'pass', 'large-only': '**large only**', fail: '**FAIL**' };
const lines = [];
lines.push('# Token contrast (WCAG 1.4.3, 1.4.11)');
lines.push('');
lines.push('Generated by `e2e/audit/contrast.mjs` from `packages/design-tokens/src/sonar.css`; do not edit by hand.');
lines.push('Translucent tokens are composited over the surface the way the browser paints them. Ratios are rounded **down** to two decimals.');
lines.push('');
lines.push('Thresholds: text 4.5:1 (normal), 3:1 for large text (≥ 24 px, or ≥ 18.66 px bold); non-text 3:1 (WCAG 1.4.11: component boundaries that identify a control, focus indicators, chart marks). "large only" means the pair passes only for large text. Hairlines (`line-*`) are decorative where they only separate panels; they must meet 3:1 where they are the only boundary of a control (`.sf-field` uses `--sf-line`, `.sf-btn` uses `--sf-line-strong`).');
lines.push('');
const failures = rows.filter((r) => r.verdict !== 'pass');
lines.push('## Summary');
lines.push('');
lines.push('| Theme | Kind | Pairs | Pass | Large only | Fail |');
lines.push('|---|---|---:|---:|---:|---:|');
for (const theme of Object.keys(themes)) {
  for (const kind of ['text', 'non-text']) {
    const set = rows.filter((r) => r.theme === theme && r.kind === kind);
    lines.push(`| ${theme} | ${kind} | ${set.length} | ${set.filter((r) => r.verdict === 'pass').length} | ${set.filter((r) => r.verdict === 'large-only').length} | ${set.filter((r) => r.verdict === 'fail').length} |`);
  }
}
lines.push('');
lines.push('## Token usage in the three apps');
lines.push('');
lines.push('Occurrences in `apps/{admin-web,member-pwa,website}/src` (tests excluded): `text-<token>` utility classes and `var(--sf-<token>)` references. A failing token that is used often as text is a systemic finding.');
lines.push('');
lines.push('| Token | `text-` class uses | `var()` uses |');
lines.push('|---|---:|---:|');
for (const [token, n] of Object.entries(used)) lines.push(`| \`${token}\` | ${n.textClass} | ${n.cssVar} |`);
lines.push('');

for (const theme of Object.keys(themes)) {
  for (const kind of ['text', 'non-text']) {
    const tokens = kind === 'text' ? TEXT : NON_TEXT;
    const set = rows.filter((r) => r.theme === theme && r.kind === kind && !r.surface.endsWith('(fill)'));
    const surfaces = [...new Set(set.map((r) => r.surface))];
    lines.push(`## ${theme === 'dark' ? 'Dark' : 'Light'} theme: ${kind} tokens × surfaces`);
    lines.push('');
    lines.push(`| ${kind === 'text' ? 'Text' : 'Non-text'} token | ${surfaces.map((s) => `${s} (${set.find((r) => r.surface === s).surfaceHex})`).join(' | ')} |`);
    lines.push(`|---|${surfaces.map(() => '---:').join('|')}|`);
    for (const token of tokens) {
      const cells = surfaces.map((s) => {
        const r = set.find((x) => x.surface === s && x.token === token);
        return r.verdict === 'pass' ? `${r.ratio.toFixed(2)}` : `${r.ratio.toFixed(2)} ${mark[r.verdict]}`;
      });
      lines.push(`| \`${token}\` (${themes[theme][token]}) | ${cells.join(' | ')} |`);
    }
    lines.push('');
  }
  const fills = rows.filter((r) => r.theme === theme && r.surface.endsWith('(fill)'));
  lines.push(`## ${theme === 'dark' ? 'Dark' : 'Light'} theme: text on saturated fills`);
  lines.push('');
  lines.push('| Text | Fill | Ratio | Verdict |');
  lines.push('|---|---|---:|---|');
  for (const r of fills) lines.push(`| \`${r.token}\` | ${r.surface} ${r.surfaceHex} | ${r.ratio.toFixed(2)} | ${mark[r.verdict]} |`);
  lines.push('');
}

lines.push('## Every pair below threshold');
lines.push('');
lines.push('| Theme | Kind | Token | Surface | Ratio | Verdict |');
lines.push('|---|---|---|---|---:|---|');
for (const r of failures) lines.push(`| ${r.theme} | ${r.kind} | \`${r.token}\` | ${r.surface} | ${r.ratio.toFixed(2)} | ${mark[r.verdict]} |`);
lines.push('');

mkdirSync(DOCS_DIR, { recursive: true });
writeFileSync(resolve(DOCS_DIR, 'contrast.md'), lines.join('\n'));
console.log(`contrast: ${rows.length} pairs, ${failures.length} below threshold → docs/ux-audit/contrast.md`);
